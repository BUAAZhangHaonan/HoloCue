def test_infusion_original_details_survive_glb_roundtrip(infusion,identifier):
    actual=infusion['local_roundtrip'][identifier]
    expected=infusion['baseline']['mesh_fingerprints'][identifier]
    if identifier=='STOPCOCK':
        # The old two meshes are immutable reference surfaces. Their internal
        # overlap is intentionally removed; visible shape/material still match.
        for node,signature in expected.items():
            assert _fingerprint(infusion['historical_stopcock'][node])==signature
        _assert_original_union_exterior(infusion,actual)
        return
    for node,signature in expected.items():
        assert node in actual,('removed original node',identifier,node)
        assert _fingerprint(actual[node])==signature,('changed original detail',identifier,node)


