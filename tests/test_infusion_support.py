def _meshes(scene, pose=None):
    result={}
    for node in scene.graph.nodes_geometry:
        transform,name=scene.graph[node]
        mesh=scene.geometry[name].copy()
        mesh.apply_transform(transform if pose is None else matrix(pose)@transform)
        result[str(node)]=mesh
    return result


def _fingerprint(mesh):
    """Hash explicit arrays/material properties, independent of GLB packing."""
    result={key:hashlib.sha256(np.asarray(getattr(mesh,key),dtype=dtype).tobytes()).hexdigest()
            for key,dtype in [('vertices','<f8'),('faces','<i8'),('vertex_normals','<f8')]}
    result['uv']=None if mesh.visual.uv is None else hashlib.sha256(
        np.asarray(mesh.visual.uv,dtype='<f8').tobytes()).hexdigest()
    material=mesh.visual.material
    texture=getattr(material,'baseColorTexture',None)
    properties={'name':material.name,'baseColorFactor':np.asarray(material.baseColorFactor).tolist(),
                'metallicFactor':material.metallicFactor,'roughnessFactor':material.roughnessFactor,
                'doubleSided':material.doubleSided,'alphaMode':material.alphaMode,
                'texture_sha256':None if texture is None else hashlib.sha256(np.asarray(texture).tobytes()).hexdigest()}
    result['material']=hashlib.sha256(json.dumps(properties,sort_keys=True).encode()).hexdigest()
    return result


def _object_contracts(spec):
    return {obj.object_id:{'pose':obj.pose.model_dump(mode='json'),
                          'interaction':obj.interaction.model_dump(mode='json'),
                          'size_m':list(obj.size_m)} for obj in spec.objects}


